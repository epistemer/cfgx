// Package loader runs a user's schema and returns its IR (ADR 0002). It
// writes a temporary main package that blank-imports the schema and runs it
// with `go run -overlay`, so nothing is written to the user's tree.
package loader

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"

	"github.com/epistemer/cfgx/internal/ir"
)

// VirtualDir is the overlay-only directory, inside the schema's directory,
// where the temporary main package appears to live.
const VirtualDir = "zz_cfgx_gen_main"

const mainSrc = `// Code generated by cfgx to run a schema. It is never written to disk.

package main

import (
	"fmt"
	"os"

	"github.com/epistemer/cfgx/dsl"
	_ %q
)

func main() {
	f, err := os.Create(os.Args[1])
	if err == nil {
		err = dsl.Export(f)
		if cerr := f.Close(); err == nil {
			err = cerr
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "cfgx:", err)
		os.Exit(1)
	}
}
`

// Load resolves pattern (such as ./schema) from workDir, runs the schema and
// returns its IR. The run is stopped after timeout.
func Load(ctx context.Context, pattern, workDir string, timeout time.Duration) (*ir.App, error) {
	importPath, dir, err := resolve(ctx, pattern, workDir)
	if err != nil {
		return nil, err
	}
	if _, err := os.Stat(filepath.Join(dir, VirtualDir)); err == nil {
		return nil, fmt.Errorf("%s exists in %s; cfgx needs that name for its temporary main package, so rename or remove it", VirtualDir, dir)
	}

	tmp, err := os.MkdirTemp("", "cfgx-gen-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(tmp)
	mainFile := filepath.Join(tmp, "main.go")
	if err := os.WriteFile(mainFile, fmt.Appendf(nil, mainSrc, importPath), 0o644); err != nil {
		return nil, err
	}
	irFile := filepath.Join(tmp, "ir.json")

	goflags, overlay, err := mergeOverlay(os.Getenv("GOFLAGS"), filepath.Join(dir, VirtualDir, "main.go"), mainFile)
	if err != nil {
		return nil, err
	}
	overlayFile := filepath.Join(tmp, "overlay.json")
	if err := os.WriteFile(overlayFile, overlay, 0o644); err != nil {
		return nil, err
	}

	ctx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()
	cmd := exec.CommandContext(ctx, "go", "run", "-overlay="+overlayFile, "./"+VirtualDir, irFile)
	cmd.Dir = dir
	cmd.Env = append(withoutEnv(os.Environ(), "GOFLAGS", "PWD"), "GOFLAGS="+goflags, "PWD="+dir)
	var stderr bytes.Buffer
	cmd.Stdout = &stderr // output from the schema's init must not reach our stdout
	cmd.Stderr = &stderr
	prepare(cmd)
	if err := cmd.Run(); err != nil {
		if ctx.Err() == context.DeadlineExceeded {
			return nil, fmt.Errorf("running the schema %s took longer than %s; something in its package initialization hangs. Its output:\n%s", importPath, timeout, tail(stderr.String(), 200))
		}
		return nil, fmt.Errorf("running the schema %s failed:\n%s", importPath, strings.TrimSpace(stderr.String()))
	}

	f, err := os.Open(irFile)
	if err != nil {
		return nil, fmt.Errorf("the schema %s ran but produced no IR: %w", importPath, err)
	}
	defer f.Close()
	return ir.Decode(f)
}

// resolve turns a pattern into an import path and a canonical directory.
// -e lets a schema with errors through, so its compile error comes from
// go run, with file and line.
func resolve(ctx context.Context, pattern, workDir string) (importPath, dir string, err error) {
	cmd := exec.CommandContext(ctx, "go", "list", "-e", "-f", "{{.ImportPath}}\t{{.Dir}}", pattern)
	cmd.Dir = workDir
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return "", "", fmt.Errorf("finding the schema package %s: %v\n%s", pattern, err, strings.TrimSpace(stderr.String()))
	}
	lines := strings.Split(strings.TrimSpace(string(out)), "\n")
	if len(lines) != 1 {
		return "", "", fmt.Errorf("%s matches %d packages; name exactly one schema package", pattern, len(lines))
	}
	importPath, dir, ok := strings.Cut(lines[0], "\t")
	if !ok || importPath == "" || dir == "" {
		return "", "", fmt.Errorf("can't find the schema package %s", pattern)
	}
	if real, err := filepath.EvalSymlinks(dir); err == nil {
		dir = real
	}
	return importPath, dir, nil
}

// mergeOverlay builds the overlay that adds the temporary main, merged with
// any -overlay already in GOFLAGS, and returns GOFLAGS without that flag.
func mergeOverlay(goflags, virtual, real string) (string, []byte, error) {
	replace := map[string]string{}
	var kept []string
	fields := strings.Fields(goflags)
	for i := 0; i < len(fields); i++ {
		f := fields[i]
		name, val, hasVal := strings.Cut(strings.TrimLeft(f, "-"), "=")
		if !strings.HasPrefix(f, "-") || name != "overlay" {
			kept = append(kept, f)
			continue
		}
		if !hasVal {
			if i+1 >= len(fields) {
				return "", nil, errors.New("GOFLAGS has -overlay without a file")
			}
			i++
			val = fields[i]
		}
		data, err := os.ReadFile(val)
		if err != nil {
			return "", nil, fmt.Errorf("reading the -overlay file in GOFLAGS: %w", err)
		}
		var user struct{ Replace map[string]string }
		if err := json.Unmarshal(data, &user); err != nil {
			return "", nil, fmt.Errorf("reading the -overlay file in GOFLAGS: %w", err)
		}
		for k, v := range user.Replace {
			replace[k] = v
		}
	}
	replace[virtual] = real
	data, err := json.Marshal(map[string]any{"Replace": replace})
	return strings.Join(kept, " "), data, err
}

func withoutEnv(env []string, names ...string) []string {
	out := env[:0:0]
	for _, kv := range env {
		name, _, _ := strings.Cut(kv, "=")
		drop := false
		for _, n := range names {
			if strings.EqualFold(name, n) {
				drop = true
			}
		}
		if !drop {
			out = append(out, kv)
		}
	}
	return out
}

func tail(s string, lines int) string {
	ls := strings.Split(strings.TrimRight(s, "\n"), "\n")
	if len(ls) > lines {
		ls = append([]string{"..."}, ls[len(ls)-lines:]...)
	}
	return strings.Join(ls, "\n")
}
