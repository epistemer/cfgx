// Package loader runs a user's schema and returns its IR (ADR 0002). It
// compiles a temporary main package that blank-imports the schema with
// `go build -overlay`, so nothing is written to the user's tree, then runs
// the binary under a timeout.
package loader

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"time"

	"github.com/epistemer/cfgx/internal/ir"
)

// VirtualDir is the overlay-only directory, inside the working directory,
// where the temporary main package appears to live. It sits in the caller's
// own module, so the caller's go.mod, replace directives, vendor directory and
// internal/ visibility all apply.
const VirtualDir = "zz_cfgx_gen_main"

const mainSrc = `// Code generated by cfgx to run a schema. It is never written to disk.

package main

import (
	"fmt"
	"os"

	"github.com/epistemer/cfgx/dsl"
	_ %q
)

func main() {
	f, err := os.Create(os.Args[1])
	if err == nil {
		err = dsl.Export(f)
		if cerr := f.Close(); err == nil {
			err = cerr
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "cfgx:", err)
		os.Exit(1)
	}
}
`

// Load resolves pattern (such as ./schema) from workDir, runs the schema and
// returns its IR. Running the schema, not compiling it, is stopped after
// timeout.
func Load(ctx context.Context, pattern, workDir string, timeout time.Duration) (*ir.App, error) {
	if real, err := filepath.EvalSymlinks(workDir); err == nil {
		workDir = real
	}
	// The two go command lookups are independent, so they run in parallel.
	type flagsResult struct {
		goflags string
		err     error
	}
	flagsCh := make(chan flagsResult, 1)
	go func() {
		g, err := goEnvGOFLAGS(ctx, workDir)
		flagsCh <- flagsResult{g, err}
	}()
	importPath, err := resolve(ctx, pattern, workDir)
	flags := <-flagsCh
	if err != nil {
		return nil, err
	}
	if flags.err != nil {
		return nil, flags.err
	}
	virtualDir := filepath.Join(workDir, VirtualDir)
	if _, err := os.Stat(virtualDir); err == nil {
		return nil, fmt.Errorf("%s exists; cfgx needs that name for its temporary main package, so rename or remove it", virtualDir)
	}

	tmp, err := os.MkdirTemp("", "cfgx-gen-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(tmp)
	mainFile := filepath.Join(tmp, "main.go")
	if err := os.WriteFile(mainFile, fmt.Appendf(nil, mainSrc, importPath), 0o644); err != nil {
		return nil, err
	}

	env, overlay, err := buildEnv(flags.goflags, workDir, filepath.Join(virtualDir, "main.go"), mainFile)
	if err != nil {
		return nil, err
	}
	overlayFile := filepath.Join(tmp, "overlay.json")
	if err := os.WriteFile(overlayFile, overlay, 0o644); err != nil {
		return nil, err
	}

	bin := filepath.Join(tmp, "schema")
	if runtime.GOOS == "windows" {
		bin += ".exe"
	}
	build := exec.CommandContext(ctx, "go", "build", "-overlay="+overlayFile, "-o", bin, "./"+VirtualDir)
	build.Dir, build.Env = workDir, env
	if out, err := build.CombinedOutput(); err != nil {
		return nil, fmt.Errorf("the schema %s doesn't compile:\n%s", importPath, strings.TrimSpace(string(out)))
	}

	irFile := filepath.Join(tmp, "ir.json")
	runCtx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()
	run := exec.CommandContext(runCtx, bin, irFile)
	run.Dir = workDir
	var output bytes.Buffer
	run.Stdout = &output // output from the schema's init must not reach our stdout
	run.Stderr = &output
	prepare(run)
	if err := run.Run(); err != nil {
		if runCtx.Err() == context.DeadlineExceeded {
			return nil, fmt.Errorf("running the schema %s took longer than %s; something in its package initialization hangs. Its output:\n%s", importPath, timeout, tail(output.String(), 200))
		}
		return nil, fmt.Errorf("running the schema %s failed:\n%s", importPath, strings.TrimSpace(output.String()))
	}

	f, err := os.Open(irFile)
	if err != nil {
		return nil, fmt.Errorf("the schema %s ran but produced no IR: %w", importPath, err)
	}
	defer f.Close()
	return ir.Decode(f)
}

type listedPackage struct {
	ImportPath string
	Dir        string
	Name       string
	Error      *struct{ Err string }
}

// resolve turns a pattern into the schema's import path. -e lets a schema
// with compile errors through, so the compiler reports them with file and
// line when the temporary main is built.
func resolve(ctx context.Context, pattern, workDir string) (string, error) {
	cmd := exec.CommandContext(ctx, "go", "list", "-e", "-json", pattern)
	cmd.Dir = workDir
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("finding the schema package %s: %v\n%s", pattern, err, strings.TrimSpace(stderr.String()))
	}
	var pkgs []listedPackage
	dec := json.NewDecoder(bytes.NewReader(out))
	for {
		var p listedPackage
		if err := dec.Decode(&p); err == io.EOF {
			break
		} else if err != nil {
			return "", fmt.Errorf("reading go list output: %w", err)
		}
		pkgs = append(pkgs, p)
	}
	switch {
	case len(pkgs) == 0:
		return "", fmt.Errorf("%s matches no packages", pattern)
	case len(pkgs) > 1:
		return "", fmt.Errorf("%s matches %d packages; name exactly one schema package", pattern, len(pkgs))
	}
	p := pkgs[0]
	switch {
	case p.ImportPath == "command-line-arguments":
		return "", fmt.Errorf("%s names Go files; name the schema's package directory instead, such as ./schema", pattern)
	case p.Dir == "" && p.Error != nil:
		return "", fmt.Errorf("can't find the schema package %s: %s", pattern, p.Error.Err)
	case p.Dir == "":
		return "", fmt.Errorf("can't find the schema package %s", pattern)
	case p.Name == "main":
		return "", fmt.Errorf("the schema %s is a main package; a schema must be an importable package", p.ImportPath)
	}
	return p.ImportPath, nil
}

// goEnvGOFLAGS returns the effective GOFLAGS, from the environment or the go
// env file.
func goEnvGOFLAGS(ctx context.Context, workDir string) (string, error) {
	cmd := exec.CommandContext(ctx, "go", "env", "GOFLAGS")
	cmd.Dir = workDir
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("go env GOFLAGS: %w", err)
	}
	return strings.TrimSpace(string(out)), nil
}

// buildEnv returns the environment and overlay for the build. The overlay
// adds the temporary main. If the effective GOFLAGS already has an -overlay,
// that overlay is merged in, with relative paths made absolute, and GOFLAGS
// is passed on without it; otherwise GOFLAGS is left alone.
func buildEnv(effectiveGOFLAGS, workDir, virtual, real string) ([]string, []byte, error) {
	goflags, userOverlay, err := splitOverlayFlag(effectiveGOFLAGS)
	if err != nil {
		return nil, nil, err
	}
	replace := map[string]string{}
	env := append(withoutEnv(os.Environ(), "PWD"), "PWD="+workDir)
	if userOverlay != "" {
		if !filepath.IsAbs(userOverlay) {
			userOverlay = filepath.Join(workDir, userOverlay)
		}
		data, err := os.ReadFile(userOverlay)
		if err != nil {
			return nil, nil, fmt.Errorf("reading the -overlay file in GOFLAGS: %w", err)
		}
		var user struct{ Replace map[string]string }
		if err := json.Unmarshal(data, &user); err != nil {
			return nil, nil, fmt.Errorf("reading the -overlay file in GOFLAGS: %w", err)
		}
		base := filepath.Dir(userOverlay)
		for k, v := range user.Replace {
			if !filepath.IsAbs(k) {
				k = filepath.Join(workDir, k)
			}
			if v != "" && !filepath.IsAbs(v) {
				v = filepath.Join(base, v)
			}
			replace[k] = v
		}
		env = append(withoutEnv(env, "GOFLAGS"), "GOFLAGS="+goflags)
	}
	replace[virtual] = real
	data, err := json.Marshal(map[string]any{"Replace": replace})
	return env, data, err
}

// splitOverlayFlag removes an -overlay flag from goflags and returns its file.
func splitOverlayFlag(goflags string) (rest, overlay string, err error) {
	var kept []string
	fields := strings.Fields(goflags)
	for i := 0; i < len(fields); i++ {
		f := fields[i]
		name, val, hasVal := strings.Cut(strings.TrimLeft(f, "-"), "=")
		if !strings.HasPrefix(f, "-") || name != "overlay" {
			kept = append(kept, f)
			continue
		}
		if !hasVal {
			if i+1 >= len(fields) {
				return "", "", errors.New("GOFLAGS has -overlay without a file")
			}
			i++
			val = fields[i]
		}
		overlay = val
	}
	return strings.Join(kept, " "), overlay, nil
}

func withoutEnv(env []string, names ...string) []string {
	out := env[:0:0]
	for _, kv := range env {
		name, _, _ := strings.Cut(kv, "=")
		drop := false
		for _, n := range names {
			if strings.EqualFold(name, n) {
				drop = true
			}
		}
		if !drop {
			out = append(out, kv)
		}
	}
	return out
}

func tail(s string, lines int) string {
	ls := strings.Split(strings.TrimRight(s, "\n"), "\n")
	if len(ls) > lines {
		ls = append([]string{"..."}, ls[len(ls)-lines:]...)
	}
	return strings.Join(ls, "\n")
}
