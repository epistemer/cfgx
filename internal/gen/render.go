// Render produces the generated Go file. Output is deterministic: the same
// model always renders the same bytes.
func Render(m *Model) ([]byte, error) {
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, m); err != nil {
		return nil, err
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return buf.Bytes(), fmt.Errorf("formatting generated code (a cfgx bug): %w", err)
	}
	return src, nil
}

// lit is s as a Go string literal: a raw one when it can be, which keeps
// embedded files readable.
func lit(s string) string {
	if !strings.Contains(s, "`") && !strings.Contains(s, "\r") {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}

